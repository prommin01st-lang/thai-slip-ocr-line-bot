// nlu.js — แปลงข้อความแชทสั้น ๆ เป็นรายการรับ/จ่าย
//
//     "กาแฟ 60"            → out  60.00  "กาแฟ"
//     "จ่ายค่าไฟ 850"      → out 850.00  "ค่าไฟ"
//     "ได้เงินเดือน 30000" → in  30,000.00 "เงินเดือน"
//
// **rule ล้วน ไม่มีโมเดล** — ตอบทันที ไม่กิน RAM ลง VPS 2 cores ได้สบาย
// ถ้าวันหนึ่งวัดแล้วพบว่า rule พลาดเยอะค่อยเติม LLM แต่ต้องยังทำงานได้ถ้า LLM ล่ม
// (ทางที่ผิดคือใส่ LLM ก่อนแล้วค่อยวัด)
import { toCents } from "./db.js";

// คำที่ชี้ทิศทางชัดเจน — เรียง "รับ" ก่อน "จ่าย" เพราะ "ได้รับ" มีทั้งสองความหมาย
const IN_WORDS = /(?:ได้รับ|รับเงิน|เงินเดือน|โบนัส|ขายได้|โอนเข้า|เงินเข้า|รายรับ|ได้|รับ)/;
const OUT_WORDS = /(?:จ่าย|ชำระ|ซื้อ|เสีย|โอนให้|โอนไป|เงินออก|รายจ่าย|ค่า)/;

/**
 * กริยา "ให้/โอนมา" — **ทิศทางกลับด้านตามว่าใครเป็นประธาน**
 *
 * ภาษาไทยไม่มีรูปกริยาบอกทิศทาง ต่างกันแค่ลำดับคำล้วน ๆ:
 *     "พ่อให้เงิน 200"   → มีคนให้เรา  → รายรับ
 *     "ให้เงินพ่อ 200"   → เราให้เขา   → รายจ่าย
 *     "พ่อโอนให้ 200"    → รายรับ      แต่ "โอนให้พ่อ 200" → รายจ่าย
 *
 * ตัดสินจากข้อเดียว: **มีประธานนำหน้ากริยาไหม** ถ้ามี = คนอื่นเป็นผู้ให้ = เรารับ
 * และประธานนั้นต้องไม่ใช่คำที่บอกว่าเราเป็นคนจ่ายอยู่แล้ว ("จ่ายให้พ่อ", "ค่าขนมให้น้อง")
 *
 * ไม่ครอบคลุมทุกรูปประโยค — แต่ครอบคลุมรูปที่คนพิมพ์จริงเกือบทั้งหมด
 * ที่เหลือยังมีปุ่มสลับทิศทางในการ์ดให้กดแก้ได้ทันที
 */
const GIVE_VERB = /(?:โอนให้|โอนมา|ส่งมา|ให้มา|ให้)/;

// จำนวนเงิน: 60 / 1,234 / 45.50 — ไม่บังคับทศนิยม (คนพิมพ์เร็ว ๆ ไม่ใส่)
const AMOUNT = /(\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)/;

// คำสั่งของบอท — **ห้ามตีความเป็นรายการเด็ดขาด**
//
// สำคัญมาก: คำสั่งที่พิมพ์ไม่ครบต้องตกมาที่นี่ ไม่ใช่ไปสร้างรายการใหม่
// เคสจริงที่เจอ: ผู้ใช้กดปุ่ม "แก้ยอด" (เติม "แก้ 12 " ให้) แล้วกดส่งโดยไม่พิมพ์ยอด
// → เดิมจะกลายเป็น "บันทึกรายจ่าย 12 บาท ชื่อ แก้" ซึ่งผิดและงงมาก
//
// ⚠️ ห้ามใช้ `\b` ปิดท้าย — `\b` นิยามจาก [A-Za-z0-9_] อักษรไทยไม่นับเป็น word char
//    "แก้\b" จึงไม่เคยแมตช์ "แก้ 12" เลย ต้องใช้ lookahead ว่าตามด้วยเว้นวรรค/ตัวเลข/จบสตริง
//    (แบบนี้ "แก้วกาแฟ 60" ยังเป็นรายการปกติ เพราะหลัง "แก้" เป็น "ว")
const COMMANDS = /^(?:สรุปทั้งหมด|สรุปสัปดาห์|สรุป|สถานะ|ตั้งค่า|ยินยอม|ยอมรับ|ตกลง|ยืนยันลบ|ลบข้อมูลของฉัน|ข้อมูลของฉัน|เตือนรายสัปดาห์|รายการ|เลิกเชื่อมชีต|เชื่อมชีต|ชีต|แก้|ลบ|งบ|help|status|summary|consent|settings|list|budget|weekly|sheets?)(?=\s|\d|$)/i;

/**
 * ข้อความ → {direction, amountCents, amount, note} หรือ null ถ้าตีความไม่ได้
 *
 * คืน null ดีกว่าเดามั่ว — ผู้เรียกจะได้ตอบว่า "ไม่เข้าใจ" แทนที่จะบันทึกผิด
 */
export function parseEntry(text) {
  const raw = String(text ?? "").trim();
  if (!raw || COMMANDS.test(raw)) return null;

  const m = AMOUNT.exec(raw);
  if (!m) return null;

  const cents = toCents(m[1].includes(".") ? m[1] : `${m[1]}.00`);
  if (cents === null || cents === 0) return null;

  // ข้อความที่เหลือหลังตัดจำนวนเงินและหน่วยออก = คำอธิบายรายการ
  const note = raw
    .replace(m[0], " ")
    .replace(/บาท|฿|thb/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

  // ดูคำชี้ทิศทางจากข้อความเต็ม (รวมส่วนที่เป็นคำกริยา)
  const inHit = IN_WORDS.exec(raw);
  const outHit = OUT_WORDS.exec(raw);

  // "<ประธาน>ให้/โอนมา" = คนอื่นเป็นผู้ให้ → เรารับ (ดูคอมเมนต์ที่ GIVE_VERB)
  // ต้องเช็คก่อนกฎ in/out ปกติ เพราะ "โอนให้" อยู่ใน OUT_WORDS ด้วย
  // "พ่อโอนให้ 200" จึงชนกันเองที่ตำแหน่งเดียวกัน แล้วแพ้ให้ out ถ้าเทียบด้วย index
  const gv = GIVE_VERB.exec(raw);
  const giverFirst = !!gv && gv.index > 0 && !OUT_WORDS.test(raw.slice(0, gv.index));

  let direction;
  if (giverFirst && (!outHit || outHit.index >= gv.index)) direction = "in";
  else if (inHit && !outHit) direction = "in";
  else if (outHit && !inHit) direction = "out";
  else if (inHit && outHit) direction = inHit.index < outHit.index ? "in" : "out";
  else direction = "out";   // ไม่มีคำกริยาเลย → คนบันทึกรายจ่ายบ่อยกว่ารายรับมาก

  return {
    direction,
    amountCents: cents,
    note: note || null,
    // บอกว่าเดาทิศทางเอาหรือมีคำยืนยัน — ผู้เรียกเอาไปตัดสินว่าจะถามซ้ำไหม
    guessed: !inHit && !outHit && !giverFirst,
  };
}

/**
 * ตัวคั่นระหว่างรายการ — **ต้องมีตัวคั่นชัดเจนเท่านั้นถึงจะแยก**
 *
 * ตั้งใจไม่แยกจากช่องว่างเปล่า ๆ ("กาแฟ 60 ข้าว 50") เพราะแยกผิดเงียบ ๆ
 * แย่กว่าบันทึกรายการเดียว — "ค่าน้ำ 3 เดือน 450" ก็มีสองตัวเลขเหมือนกัน
 * แต่เป็นรายการเดียว ไม่มีทางแยกสองเคสนี้ออกจากกันด้วยกฎ
 *
 * ⚠️ จุลภาคเป็นตัวคั่นหลักหลักพันด้วย ("12,500") — lookahead กันไว้:
 * จุลภาคที่ตามด้วยเลข 3 หลักพอดีแล้วไม่มีเลขต่อ = อยู่ในตัวเลข ห้ามแยก
 */
const SPLIT = /\r?\n|[+;·•]|,(?!\d{3}(?!\d))/;

/**
 * ข้อความ → หลายรายการ `{ entries, skipped, ambiguous }`
 *
 * `skipped`  = ท่อนที่มีตัวคั่นแต่ตีความไม่ได้ — ต้องบอกผู้ใช้ ไม่ใช่ทิ้งเงียบ
 * `ambiguous`= ไม่มีตัวคั่นแต่มีตัวเลขหลายตัว → อาจตั้งใจพิมพ์หลายรายการ
 *              บันทึกรายการเดียวตามเดิม แล้วค่อยบอกวิธีคั่นในหมายเหตุ
 */
export function parseEntries(text) {
  const raw = String(text ?? "").trim();
  // คำสั่งบอทต้องถูกปฏิเสธที่ข้อความ **เต็ม** ก่อนแยกเสมอ
  // ไม่งั้น "งบ อาหาร 5000, 3000" จะถูกหั่นจนคำสั่งหลุดกลายเป็นรายการ
  if (!raw || COMMANDS.test(raw)) return { entries: [], skipped: [], ambiguous: false };

  const parts = raw.split(SPLIT).map((s) => s.trim()).filter(Boolean);

  if (parts.length < 2) {
    const one = parseEntry(raw);
    // นับตัวเลขที่หน้าตาเหมือนยอด — สองตัวขึ้นไปแปลว่าอาจตั้งใจพิมพ์หลายรายการ
    const nums = raw.match(new RegExp(AMOUNT.source, "g")) ?? [];
    return {
      entries: one ? [one] : [],
      skipped: [],
      ambiguous: !!one && nums.length > 1,
    };
  }

  const entries = [], skipped = [];
  for (const p of parts) {
    const e = parseEntry(p);
    if (e) entries.push(e); else skipped.push(p);
  }
  return { entries, skipped, ambiguous: false };
}
