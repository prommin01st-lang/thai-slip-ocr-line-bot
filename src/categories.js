const BY_KEY = new Map(CATEGORIES.map((c) => [c.key, c]));

/** '🍜 อาหาร' — ใช้แสดงในการ์ด ไม่ใช่ค่าที่เก็บลง DB */
export function labelOf(key) {
  if (!key) return null;
  const c = BY_KEY.get(key);
  return c ? `${c.emoji} ${c.key}` : key;
}

export const isCategory = (key) => BY_KEY.has(key);

/**
 * เดาหมวดจากข้อความ — คืน `key` หรือ null ถ้าไม่มีคำไหนตรง
 *
 * **เลือกคำที่ยาวที่สุดที่ตรง ไม่ใช่คำแรกที่เจอ** เพราะคำสั้นมักซ้อนอยู่ในคำยาว
 * ที่คนละความหมาย เช่น "ค่าน้ำ" (บิล) มี "น้ำ" ซ้อนอยู่ และ "น้ำมัน" (เดินทาง)
 * ก็มี "น้ำ" เหมือนกัน ถ้าเอาคำแรกที่เจอ ผลจะขึ้นกับลำดับในอาเรย์ซึ่งเปราะมาก
 */
export function guessCategory(text) {
  if (!text) return null;
  const s = String(text).toLowerCase();
  let best = null, bestLen = 0;
  for (const c of CATEGORIES) {
    for (const w of c.words) {
      if (w.length > bestLen && s.includes(w)) { best = c.key; bestLen = w.length; }
    }
  }
  return best;
}

/**
 * หมวดที่จะเอาขึ้นเป็นปุ่มให้กด — หมวดที่เดาได้ต้องไม่อยู่ในนี้ (กดซ้ำไม่มีประโยชน์)
 * เอาแค่ 4 อัน ที่เหลือซ่อนหลังปุ่ม "อื่นๆ" ไม่งั้นการ์ดยาวจนต้องเลื่อน
 */
export function pickerFor(current, limit = 4) {
  return CATEGORIES.filter((c) => c.key !== current && c.key !== "อื่นๆ").slice(0, limit);
}
